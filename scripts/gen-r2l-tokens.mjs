#!/usr/bin/env node
// Generates src/styles/r2l-tokens.css mechanically from the locked design handoff.
// Usage: node scripts/gen-r2l-tokens.mjs <design-system-dir> [out-file]
//   <design-system-dir> holds tokens.css (the :root block is copied verbatim; no value is retyped here).
//   Default design dir: _design/read2lead-dao-phieu-luu/design-system, if present.
// The @import of fonts.css is dropped (fonts are self-hosted via r2l-fonts.css).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(process.argv[2] || resolve(root, '_design/read2lead-dao-phieu-luu/design-system'));
const out = resolve(process.argv[3] || resolve(root, 'src/styles/r2l-tokens.css'));
const src = resolve(dir, 'tokens.css');
if (!existsSync(src)) {
  console.error(`gen-r2l-tokens: ${src} not found. Pass the design-system directory as the first argument.`);
  process.exit(2);
}
const css = readFileSync(src, 'utf8');
const m = css.match(/:root\s*\{[\s\S]*?\n\}/);
if (!m) { console.error('gen-r2l-tokens: no :root block found in tokens.css'); process.exit(2); }
const header = `/* GENERATED by scripts/gen-r2l-tokens.mjs from the locked design (design-system/tokens.css).\n   Do not edit by hand. Read2Lead · Đảo phiêu lưu design tokens. */\n`;
writeFileSync(out, header + m[0] + '\n');
console.log(`wrote ${out} (${(m[0].match(/--r2l-[a-z0-9-]+:/g) || []).length} tokens)`);
