#!/usr/bin/env node
/**
 * Auto-generate JS module wrapper for monster-parts.json.
 * Reason: native JSON imports break Cloudflare Pages Functions esbuild
 * (doesn't support `with { type: 'json' }`), and plain imports require
 * the attribute on Node 22. JS module = no attribute = both happy.
 *
 * Run after editing monster-parts.json.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const JSON_PATH = path.resolve(__dirname, '../public/assets/monsters/monster-parts.json');
const OUT_PATH = path.resolve(__dirname, '../functions/api/_monster-parts-data.mjs');

const data = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'));
const body = `// AUTO-GENERATED by scripts/gen-monster-parts-mjs.mjs. DO NOT EDIT DIRECTLY.
// Source: public/assets/monsters/monster-parts.json
// Reason: Cloudflare Pages Functions esbuild doesn't support JSON import attributes.

export default ${JSON.stringify(data, null, 2)};
`;
fs.writeFileSync(OUT_PATH, body, 'utf8');
console.log(`Wrote ${OUT_PATH} (${Object.keys(data).length} slots, ${body.length} bytes)`);
